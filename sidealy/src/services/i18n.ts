export function useTranslation() {
  let language = "en";
  try {
    const app = useApp();
    if (app?.language) language = app.language;
  } catch {
    // Outside of AppProvider (e.g. isolated unit tests)
  }
  const langKey = (language === "fr" || language === "es" || language === "en" ? language : "en") as LanguageCode;
  const dict = DICTIONARIES[langKey] || DICTIONARIES.en;

  const t = (key: string, fallback?: string): string => {
    return dict[key] ?? fallback ?? key;
  };

  /** Interpolate `{key}` placeholders: `ti("auth.checkMailVerify", { email })` */
  const ti = (key: string, vars: Record<string, string | number>, fallback?: string): string => {
    let result = t(key, fallback);
    for (const [k, v] of Object.entries(vars)) {
      result = result.replaceAll(`{${k}}`, String(v));
    }
    return result;
  };

  return { t, ti, language: langKey };
}
